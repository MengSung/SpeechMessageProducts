"""檔案整體說明

目的與定位：保護文件守門會拒絕缺漏、假標記、損壞編碼及越界來源，避免只有漂亮報表卻未納管新檔。
主要功能與流程：在獨立暫存樹注入未寫檔頭的新來源、重複伴隨身分、BOM、LF及外部link，斷言固定原因。
使用邊界與維護：所有來源皆為合成資料，不讀產品設定、不建立Host或外部連線；TemporaryDirectory擁有測試樹並於結束清理。
符號連結案例只在平台允許建立link時執行，其餘案例不依賴權限、網路、計時或真實Git索引。
"""

import importlib.util
import json
from pathlib import Path
import tempfile
import unittest

SPEC=importlib.util.spec_from_file_location('file_documentation',Path(__file__).resolve().parents[1]/'check_file_documentation.py')
CHECKER=importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(CHECKER)
OVERVIEW='/*\r\n檔案整體說明\r\n目的與定位：'+('讀取受控來源並驗證完整候選。'*10)+'\r\n主要功能與流程：先驗證再發布。\r\n使用邊界與維護：輸入由操作擁有。\r\n*/\r\n'


class FileDocumentationTests(unittest.TestCase):
    """以可觀察失敗原因驗證文件政策，不把任意例外當成拒絕成功。"""

    def test_missing_and_embedded_markers_do_not_count(self):
        for value in ('class A {}\r\n', 'var text="檔案整體說明";\r\n', 'class A {}\r\n'+OVERVIEW):
            self.assertIn('MissingFileOverview',CHECKER.inspect_bytes(value.encode(),'.cs'))

    def test_valid_comment_and_generated_banner_are_accepted(self):
        for prefix in ('', '// <auto-generated>fixed</auto-generated>\r\n'):
            self.assertEqual([],CHECKER.inspect_bytes((prefix+OVERVIEW+'class A {}\r\n').encode(),'.cs'))

    def test_byte_faults_and_boilerplate_are_rejected(self):
        self.assertIn('BOM',CHECKER.inspect_bytes(b'\xef\xbb\xbf'+OVERVIEW.encode(),'.cs'))
        self.assertIn('CrlfRequired',CHECKER.inspect_bytes(OVERVIEW.replace('\r\n','\n').encode(),'.cs'))
        self.assertIn('InvalidUtf8',CHECKER.inspect_bytes(b'\xff\r\n','.cs'))
        self.assertIn('PlaceholderOverview',CHECKER.inspect_bytes(OVERVIEW.replace('先驗證再發布','已修復的說明').encode(),'.cs'))

    def test_new_product_sources_are_included_but_vendor_and_build_outputs_are_excluded(self):
        for path in ('FutureProduct/Worker.cs','FutureProduct/appsettings.json','NewTool/entry.py'):
            self.assertNotEqual('reference',CHECKER.classification(path))
        for path in ('Other/bin/Build.cs','PowerPlatform.Dataverse.Client/OnPremiseClient.cs','.worktrees/other/a.cs'):
            self.assertEqual('reference',CHECKER.classification(path))
        self.assertEqual('inline',CHECKER.classification('NewProduct/Resource.g.cs'))

    def test_new_source_and_json_require_their_own_explanations(self):
        with tempfile.TemporaryDirectory() as directory:
            root=Path(directory);(root/'docs').mkdir();(root/'New').mkdir()
            (root/CHECKER.COMPANIONS).write_text('{}',encoding='utf-8')
            (root/'New/A.cs').write_bytes(b'class A {}\r\n')
            _,failures=CHECKER.check(root,['New/A.cs','New/settings.json'])
            self.assertIn(('New/A.cs','MissingFileOverview'),failures)
            self.assertIn(('New/settings.json','MissingCompanionExplanation'),failures)

    def test_duplicate_companion_identities_are_not_silently_overwritten(self):
        with self.assertRaisesRegex(ValueError,'DuplicateCompanionIdentity'):
            json.loads('{"a":"first","a":"second"}',object_pairs_hook=CHECKER.reject_duplicate_keys)

    def test_parent_paths_and_external_links_are_rejected(self):
        with tempfile.TemporaryDirectory() as directory:
            root=Path(directory)
            with self.assertRaisesRegex(ValueError,'UnsafePath'): CHECKER.read_owned(root,'../outside.cs')
            with self.assertRaisesRegex(ValueError,'UnsafePath'): CHECKER.read_owned(root,'C:/outside.cs')
            (root/'target.cs').write_bytes(b'private fixture')
            try: (root/'link.cs').symlink_to(root/'target.cs')
            except OSError: return
            with self.assertRaisesRegex(ValueError,'ReparsePoint'): CHECKER.read_owned(root,'link.cs')


if __name__=='__main__':
    unittest.main()
