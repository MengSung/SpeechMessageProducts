"""檔案整體說明

目的與定位：唯讀檢查目前Git工作樹自行維護的程式與設定，防止新增／修改後遺漏繁中檔案導讀。
主要功能與流程：從Git取得NUL分隔路徑；依明確來源邊界檢查原生註解、UTF-8及伴隨說明。
使用邊界與維護：不執行產品、不連遠端、不讀設定值或輸出來源本文；每檔最多16MiB。
Git子程序有30秒期限，檔案讀取後即釋放handle；拒絕link／junction，不跨工作樹讀取。
語法守門只證明結構存在；說明是否符合實際責任、授權及資源所有權仍須由變更審查確認。
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys

INLINE_EXTENSIONS = frozenset({
    '.cs', '.cshtml', '.js', '.cjs', '.ts', '.css', '.ps1', '.py', '.bat',
    '.csproj', '.props', '.targets', '.resx', '.config', '.yml', '.yaml',
})
COMPANION_EXTENSIONS = frozenset({'.json', '.sln', '.slnf', '.toml'})
EXCLUDED_ROOTS = frozenset({
    '.ccg', '.trellis', '.agents', '.claude', '.codex', '.gemini', '.opencode',
    '.serena', '.git', '.worktrees', '.其他解決方案', 'artifacts', 'scratch',
})
EXCLUDED_SEGMENTS = frozenset({'bin', 'obj', 'node_modules', 'TestResults', '.worktrees'})
REFERENCE_PREFIXES = (
    'PowerPlatform.Dataverse.Client/',
    'docs/portable/member-info-portable-kit/reference-implementation/',
    'SpeechMessageProducts.ChurchReport/文件/',
    'SpeechMessageProducts.ChurchReport/DotNetPublish/',
    'SpeechMessageProducts.ChurchReport/wwwroot/lib/',
    'SpeechMessageProducts.ChurchReport/wwwroot/assets/',
    'SpeechMessageProducts.ChurchReport/wwwroot/js/devextreme/',
    'SpeechMessageProducts.ChurchReport/wwwroot/css/devextreme/',
    'd365/snapshots/',
)
COMPANIONS = 'docs/file-purpose-companions.json'
MAX_FILE_BYTES = 16 * 1024 * 1024


def classification(relative: str) -> str:
    """以穩定路徑判斷目前維護來源，新增產品根目錄預設納管，不能靠檔名含generated跳過。"""
    parts = relative.split('/')
    if parts[0] in EXCLUDED_ROOTS or any(x in EXCLUDED_SEGMENTS for x in parts):
        return 'reference'
    if relative.startswith(REFERENCE_PREFIXES):
        return 'reference'
    extension = Path(relative).suffix.lower()
    if extension in INLINE_EXTENSIONS:
        return 'inline'
    if extension in COMPANION_EXTENSIONS:
        return 'companion'
    return 'other'


def leading_comment(source: str, extension: str) -> str:
    """只接受檔首真正註解區，不讓字串、HTML可見文字或檔案中途的標記冒充導讀。"""
    text = source.lstrip()
    if text.startswith('#!'):
        text = text.partition('\n')[2].lstrip()
    if text.startswith('<?xml'):
        text = text.partition('?>')[2].lstrip()
    if extension == '.cs' and text.startswith('// <auto-generated>'):
        text = text.partition('\n')[2].lstrip()
    delimiters = {
        '.cshtml': ('@*', '*@'), '.ps1': ('<#', '#>'),
        '.csproj': ('<!--', '-->'), '.props': ('<!--', '-->'),
        '.targets': ('<!--', '-->'), '.resx': ('<!--', '-->'), '.config': ('<!--', '-->'),
    }
    if extension in delimiters:
        start, end = delimiters[extension]
    elif extension in ('.py', '.yml', '.yaml'):
        if extension == '.py' and text.startswith(('"""', "'''")):
            start = end = text[:3]
        else:
            return '\n'.join(x[1:] for x in text.splitlines() if x.startswith('#')) if text.startswith('#') else ''
    elif extension == '.bat':
        rows=[]
        for line in text.splitlines():
            if not line.lower().startswith('@rem'): break
            rows.append(line[4:])
        return '\n'.join(rows)
    else:
        start, end = '/*', '*/'
    if not text.startswith(start):
        return ''
    stop = text.find(end, len(start))
    return text[len(start):stop] if stop >= 0 else ''


def inspect_bytes(raw: bytes, extension: str) -> list[str]:
    """檢查可發布位元組及導讀必要段落，只回傳固定代碼，不回傳來源或設定值。"""
    issues=[]
    if raw.startswith((b'\xef\xbb\xbf', b'\xff\xfe', b'\xfe\xff')):
        issues.append('BOM')
    try:
        text=raw.decode('utf-8', errors='strict')
    except UnicodeDecodeError:
        return issues + ['InvalidUtf8']
    if re.search(r'(?<!\r)\n|\r(?!\n)', text) or not raw.endswith(b'\r\n'):
        issues.append('CrlfRequired')
    comment=leading_comment(text, extension)
    if '檔案整體說明' not in comment:
        issues.append('MissingFileOverview')
    if any(label not in comment for label in ('目的與定位', '主要功能與流程', '使用邊界與維護')):
        issues.append('IncompleteFileOverview')
    if len(re.findall('[\u3400-\u9fff]', comment)) < 80:
        issues.append('InsufficientChineseExplanation')
    if any(x in comment for x in ('AI-繁體中文檔案註解', '此檔案位於服務或工具層', '已修復的說明', '\ufffd')):
        issues.append('PlaceholderOverview')
    return issues


def read_owned(root: Path, relative: str) -> bytes:
    """逐層拒絕符號連結與Windows reparse point，再有界讀取；不沿父目錄或其他工作樹後備。"""
    if '\\' in relative or Path(relative).is_absolute() or any(x in ('', '.', '..') for x in relative.split('/')):
        raise ValueError('UnsafePath')
    cursor=root
    for part in relative.split('/'):
        cursor=cursor/part
        stat=cursor.lstat()
        if cursor.is_symlink() or getattr(stat, 'st_file_attributes', 0) & 0x400:
            raise ValueError('ReparsePoint')
    with cursor.open('rb') as stream:
        raw=stream.read(MAX_FILE_BYTES+1)
    if len(raw)>MAX_FILE_BYTES:
        raise ValueError('FileBudgetExceeded')
    return raw


def reject_duplicate_keys(pairs: list[tuple[str, object]]) -> dict:
    """伴隨說明也必須有唯一檔案身分，不能以JSON最後值覆寫隱藏重複說明。"""
    result={}
    for key,value in pairs:
        if key in result:
            raise ValueError('DuplicateCompanionIdentity')
        result[key]=value
    return result


def check(root: Path, paths: list[str]) -> tuple[int, list[tuple[str, str]]]:
    """對同一份Git候選逐檔檢查，任一缺漏整體失敗；結果只包含相對路徑與固定原因。"""
    companions=json.loads(read_owned(root, COMPANIONS).decode('utf-8'), object_pairs_hook=reject_duplicate_keys)
    if not isinstance(companions, dict): raise ValueError('InvalidCompanionManifest')
    checked=0; failures=[]
    for relative in sorted(set(paths)):
        mode=classification(relative)
        if mode not in ('inline', 'companion'): continue
        checked+=1
        try:
            if mode=='companion':
                entry=companions.get(relative)
                if not isinstance(entry, str) or len(re.findall('[\u3400-\u9fff]',entry))<50:
                    failures.append((relative,'MissingCompanionExplanation'))
            else:
                for issue in inspect_bytes(read_owned(root,relative),Path(relative).suffix.lower()):
                    failures.append((relative,issue))
        except (OSError, ValueError) as error:
            failures.append((relative, str(error) if isinstance(error,ValueError) else type(error).__name__))
    return checked,failures


def main() -> int:
    """在指定工作樹執行唯讀守門，Git與解碼失敗回2、文件缺漏回1、全部通過回0。"""
    parser=argparse.ArgumentParser(description='Check Traditional Chinese file overviews without executing product code.')
    parser.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[2])
    args=parser.parse_args()
    try:
        root=args.root.resolve(strict=True)
        listing=subprocess.run(['git','-c','core.quotepath=false','ls-files','--cached','--others','--exclude-standard','-z'],
                               cwd=root,capture_output=True,check=True,timeout=30)
        paths=[p for p in listing.stdout.decode('utf-8').split('\0') if p and (root/p).exists()]
        checked,failures=check(root,paths)
        for path,reason in failures: print(f'FAIL {path}: {reason}')
        print(f'File documentation: checked={checked}, failures={len(failures)}')
        return 1 if failures else 0
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print('File documentation rejected: '+type(error).__name__)
        return 2


if __name__=='__main__':
    raise SystemExit(main())
