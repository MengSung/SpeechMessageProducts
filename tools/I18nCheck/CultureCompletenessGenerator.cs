/*
檔案整體說明

目的與定位：把方案全部原始資源的翻譯完成度編成 Localization 的純常數產物，
供 Hosting 在發布語系前守門；不把繁中回退、偽語系或空白翻譯當成已完成翻譯。
與 ResourceVerifier 一樣以全方案唯一中性鍵為分母，不依顯示文字去重。

主要功能與流程：接收 ResourceSet 完整不可變候選，先驗跨組唯一鍵、總鍵兩萬及
語系六十四上限，逐語系統計非空白原始值。全部成功後依 Ordinal 排序輸出計數與
查詢方法；沒有資源時任何語系皆未完成。輸出不包含資源本文、路徑或生成時間，
固定 UTF-8 無 BOM／CRLF，可由 generate-completeness --check 逐位元組重現。

使用邊界與維護：呼叫端負責根目錄、XML 載入與原子寫入，本檔沒有檔案、連線、
背景工作或靜態來源快取。候選字典只存活於單次 Generate；產物只含編譯常數，
不持有 request、使用者、租戶、憑證或可變集合。翻譯變更必須重生並跑 verify。
*/
using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace I18nCheck;

/// <summary>從完整原始翻譯生成有界且可重現的發布守門資料，不使用任何 fallback 值。</summary>
internal static class CultureCompletenessGenerator
{
    /// <summary>
    /// 所有中性鍵共同組成分母；每個原始語系只計非空白值，跨組同鍵直接拒絕。
    /// 此方法不發布部分候選；來源錯誤交 CLI 安全邊界處理，舊輸出保持不變。
    /// </summary>
    /// <param name="resources">同次命令在明確方案邊界內載入的完整資源候選。</param>
    /// <returns>純常數與查詢函式的 UTF-8 無 BOM／CRLF 原始碼。</returns>
    internal static byte[] Generate(IReadOnlyList<ResourceSet> resources)
    {
        ArgumentNullException.ThrowIfNull(resources);
        var keys = new HashSet<string>(StringComparer.Ordinal);
        var counts = new Dictionary<string, int>(StringComparer.Ordinal)
        {
            ["zh-TW"] = 0,
            ["en"] = 0
        };
        foreach (var resource in resources)
        {
            foreach (var key in resource.Catalog.Values["zh-TW"].Keys)
            {
                if (!keys.Add(key))
                    throw new InvalidDataException("I18N618: completeness resource identity is repeated.");
                if (keys.Count > 20_000)
                    throw new InvalidDataException("I18N619: completeness key budget exceeded.");
            }
            foreach (var culture in resource.Catalog.Values)
            {
                counts.TryAdd(culture.Key, 0);
                if (counts.Count > 64)
                    throw new InvalidDataException("I18N620: completeness culture budget exceeded.");
                counts[culture.Key] += culture.Value.Count(pair => !string.IsNullOrWhiteSpace(pair.Value));
            }
        }

        var text = new StringBuilder("""
            // <auto-generated>由 tools/I18nCheck generate-completeness 產生，請勿手改。</auto-generated>
            /*
             * 檔案整體說明
             *
             * 目的與定位：提供全方案原始資源的語系完成度，供 Hosting 啟動時驗證發布設定。
             * 主要功能與流程：TotalKeyCount 是全部唯一中性鍵數；各語系只計非空白原始翻譯，
             * 不計繁中回退或生成偽語系。所有鍵均有原始翻譯且分母大於零才算完整。
             * 使用邊界與維護：只含固定常數，不保存可變集合、request、使用者、租戶或憑證，
             * 不執行 I/O、背景工作或授權。修改 resx 後由正式 CLI 重生，generate --check
             * 與 verify 必須逐位元組一致；不得手改產物或把完成度當作業務授權。
             */
            #nullable enable
            namespace SpeechMessage.Localization
            {
                /// <summary>全方案原始翻譯完成度；只有完整翻譯才允許 Host 開放發布。</summary>
                public static class CultureCompleteness
                {
                    /// <summary>所有唯一中性資源鍵的數目，不以顯示文字合併記錄。</summary>
                    public const int TotalKeyCount =
            """);
        text.Append(' ').Append(keys.Count.ToString(CultureInfo.InvariantCulture)).Append(";\n\n");
        text.Append("        /// <summary>回傳原始非空白翻譯數；未知、空值及偽語系皆為零，沒有 fallback。</summary>\n");
        text.Append("        /// <param name=\"culture\">啟動政策中的文化代碼，以 OrdinalIgnoreCase 比對。</param>\n");
        text.Append("        /// <returns>固定計數，不保留查詢值或新增動態快取。</returns>\n");
        text.Append("        public static int GetTranslatedKeyCount(string? culture)\n        {\n");
        foreach (var pair in counts.OrderBy(pair => pair.Key, StringComparer.Ordinal))
        {
            text.Append("            if (string.Equals(culture, ")
                .Append(SyntaxFactory.Literal(pair.Key).ToFullString())
                .Append(", System.StringComparison.OrdinalIgnoreCase)) return ")
                .Append(pair.Value.ToString(CultureInfo.InvariantCulture)).Append(";\n");
        }
        text.Append("            return 0;\n        }\n\n");
        text.Append("        /// <summary>非空的全鍵集合均已翻譯才為完整；偽語系永不作正式發布依據。</summary>\n");
        text.Append("        /// <param name=\"culture\">待驗的啟動語系，不是授權或租戶識別。</param>\n");
        text.Append("        /// <returns>有真實完整翻譯時為 true，空集合亦為 false。</returns>\n");
        text.Append("        public static bool IsComplete(string? culture) =>\n");
        text.Append("            TotalKeyCount > 0 && GetTranslatedKeyCount(culture) == TotalKeyCount;\n    }\n}\n");
        return new UTF8Encoding(false, true).GetBytes(text.ToString()
            .Replace("\r\n", "\n", StringComparison.Ordinal).Replace("\n", "\r\n", StringComparison.Ordinal));
    }
}
