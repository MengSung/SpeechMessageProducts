using System.Text;
using System.Xml;
using System.Xml.Linq;
using Microsoft.CodeAnalysis.CSharp;

namespace I18nCheck;

/// <summary>
/// 將釘選 CLDR 的公共時區映射轉成無可變集合的 switch；沒有教會、使用者或憑證資料。
/// XML／串流只由單次命令持有，全部驗證後才回傳完整候選，失敗不碰既有產物。
/// </summary>
internal static class TimeZoneGenerator
{
    /// <summary>與 data/windowsZones.xml 及其來源記錄一起升級的固定 CLDR release，不以執行日期猜版本。</summary>
    internal const string PinnedCldrVersion = "49";

    /// <summary>
    /// 以最多十六 MiB XML、4096 個來源列及 2048 個唯一 IANA 限制配置量；排序採 Ordinal。
    /// 上游有外部 DTD 宣告，故僅 Ignore 宣告而不解析 DTD；XmlResolver=null 且實體引用仍由 XML reader 拒絕。
    /// </summary>
    /// <param name="path">已由 LocalFiles.Resolve 限制在選定 repo 的來源。</param>
    /// <param name="version">由維護者明確選定的數字版號；預設釘選值由 CLI 提供。</param>
    /// <returns>無 BOM UTF-8、CRLF、final CRLF 的完整生成檔。</returns>
    internal static byte[] Generate(string path, string version)
    {
        if (string.IsNullOrWhiteSpace(version) || version.Length > 20 || version.Split('.').Any(part => part.Length == 0 || part.Any(character => character is < '0' or > '9')))
            throw new InvalidDataException("I18N501: CLDR version is invalid.");
        LocalFiles.CheckFile(path);
        using var stream = File.OpenRead(path);
        using var reader = XmlReader.Create(stream, new XmlReaderSettings
        {
            DtdProcessing = DtdProcessing.Ignore,
            XmlResolver = null,
            MaxCharactersInDocument = LocalFiles.MaxFileBytes
        });
        var document = XDocument.Load(reader);
        if (document.Root?.Name != "supplementalData") throw new InvalidDataException("I18N502: CLDR root is invalid.");
        var containers = document.Root.Elements("windowsZones").ToArray();
        if (containers.Length != 1) throw new InvalidDataException("I18N503: CLDR mapping container is invalid.");
        var groups = containers[0].Elements("mapTimezones").ToArray();
        if (groups.Length != 1) throw new InvalidDataException("I18N504: CLDR mapping group is invalid.");
        var mappings = new SortedDictionary<string, string>(StringComparer.Ordinal);
        var rowCount = 0;
        foreach (var row in groups[0].Elements())
        {
            if (++rowCount > 4096 || row.Name != "mapZone") throw new InvalidDataException("I18N505: CLDR row budget or schema is invalid.");
            var windows = (string?)row.Attribute("other");
            var territory = (string?)row.Attribute("territory");
            var types = (string?)row.Attribute("type");
            if (string.IsNullOrWhiteSpace(windows) || windows.Length > 128 || windows.Any(character => !IsIdentifierCharacter(character) && character is not (' ' or '(' or ')')) ||
                string.IsNullOrWhiteSpace(territory) || territory.Length is < 2 or > 3 || territory.Any(character => character is not (>= 'A' and <= 'Z') and not (>= '0' and <= '9')) ||
                string.IsNullOrWhiteSpace(types) || types.Length > 2048)
                throw new InvalidDataException("I18N506: CLDR row fields are invalid.");
            foreach (var iana in types.Split(' ', StringSplitOptions.RemoveEmptyEntries))
            {
                if (iana.Length > 128 || iana.Any(character => !IsIdentifierCharacter(character)))
                    throw new InvalidDataException("I18N507: IANA identity is invalid.");
                if (mappings.TryGetValue(iana, out var previous))
                {
                    // CLDR 不同 territory 可重述同一公共映射；只有完全相同的值才可視為同一條規則。
                    if (!string.Equals(previous, windows, StringComparison.Ordinal)) throw new InvalidDataException("I18N508: IANA mapping conflict.");
                }
                else mappings.Add(iana, windows);
                if (mappings.Count > 2048) throw new InvalidDataException("I18N509: IANA mapping budget exceeded.");
            }
        }
        if (mappings.Count == 0) throw new InvalidDataException("I18N510: CLDR has no mappings.");
        var text = new StringBuilder("// <auto-generated>由 tools/I18nCheck generate-timezones 產生，請勿手動修改。</auto-generated>\r\n");
        text.Append("// CLDR ").Append(version).Append("；來源與 Unicode 授權見 tools/I18nCheck/data/README.md。\r\n#nullable enable\r\nnamespace SpeechMessage.Localization\r\n{\r\n");
        text.Append("    /// <summary>固定公共 IANA 對照，無可變字典、教會或 caller 狀態；不使用伺服器 local 時區。</summary>\r\n    internal static class IanaWindowsZones\r\n    {\r\n");
        text.Append("        /// <summary>以區分大小寫的固定映射查詢，未知 ID 回空值，不猜測或新增動態快取。</summary>\r\n        internal static bool TryGetWindowsId(string iana, out string windowsId)\r\n        {\r\n            windowsId = iana switch\r\n            {\r\n");
        foreach (var mapping in mappings)
            text.Append("                ").Append(SyntaxFactory.Literal(mapping.Key).ToFullString()).Append(" => ").Append(SyntaxFactory.Literal(mapping.Value).ToFullString()).Append(",\r\n");
        text.Append("                _ => string.Empty\r\n            };\r\n            return windowsId.Length != 0;\r\n        }\r\n    }\r\n}\r\n");
        return new UTF8Encoding(false, true).GetBytes(text.ToString());
    }

    /// <summary>只允許時區規格的有限 ASCII 字元，拒絕空白、引號與控制字元注入；Roslyn 仍負責最終逸出。</summary>
    private static bool IsIdentifierCharacter(char value) => value is >= 'A' and <= 'Z' or >= 'a' and <= 'z' or >= '0' and <= '9' or '/' or '_' or '-' or '+' or '.';
}
