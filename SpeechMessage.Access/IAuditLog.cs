/*
 * 檔案整體說明
 * 目的與定位：F8 跨產品修改紀錄的最小寫入契約，由產品操作流程提供單次不可變 AuditEntry，實作負責驗證與安全發布。
 * 主要功能與流程：伺服器業務owner為單一欄位修改事實持久保存非空EventId及原內容；重送沿用事件，實作以租戶／事件資料庫唯一鍵Create或精確核對既有列。呼叫端等待WriteAsync與清理結束；RecordId是被修改資料的識別值，EventId亦不取代資料庫稽核主鍵。
 * 使用邊界與維護：本介面不提供共同交易、自動重試或一般查詢，也不擁有連線、背景工作及診斷入口。呼叫端必須先完成業務授權，不能把稽核成功視為業務交易成功；不同事實即使內容相同仍使用不同事件ID。
 * 取消與資源：實作必須以單次操作為資料保留邊界，敏感前後值遮罩後才可送往儲存；同步 SDK 已入場時須等待返回才能歸還租約，不能以取消製造未完成工作的共用連線。
 */
namespace SpeechMessage.Access;

/// <summary>
/// 接收單次修改事實的稽核出口；實作仍須重新確認操作者與租戶，
/// 不得因呼叫端提供主鍵而略過伺服器身分驗證。
/// </summary>
public interface IAuditLog
{
    /// <summary>
    /// 驗證並建立一筆安全修改紀錄；相同事件須完整符合已遮罩內容，不能覆寫既有證據。
    /// 只有儲存成功或精確核對成功且租約清理結束才完成。
    /// 取消不保證已送出的 SDK 寫入未發生，不提供與業務資料的共同交易或自動重送。
    /// </summary>
    /// <param name="entry">呼叫端目前操作的不可變候選；不得包含要保留的明文秘密。</param>
    /// <param name="ct">明確的呼叫端取消訊號，不能用內部傳輸逾時冒充正常取消。</param>
    /// <returns>成功、正常取消或保留真正失敗的工作，不保留呼叫端候選供其他請求使用。</returns>
    Task WriteAsync(AuditEntry entry, CancellationToken ct = default);
}
